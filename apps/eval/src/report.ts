import { type EmbeddingDescriptor } from '@repo/ai';
import { type ChunkerOptions } from '@repo/rag';
import { type RetrievalMode } from '@repo/shared';
import { HIT_KS, type Mode, RETRIEVAL, type Strategy, type StrategyId } from './config.js';
import { type CorpusDocument } from './corpus.js';
import { EVAL_INPUT_PATHS, type CommitInfo } from './git.js';
import { formatMrr, formatRate, hitAtK, type Rank, summarize, type Summary } from './metrics.js';
import { QUESTION_TYPES, type Question } from './questions.js';
import { type RetrievalResult, type RetrievedChunk } from './retrieve.js';

export interface ReportInput {
  generatedAt: Date;
  commit: CommitInfo | null;
  /** Repository-relative path of the question file that was used. */
  questionFile: string;
  isRealSet: boolean;
  questions: readonly Question[];
  corpus: readonly CorpusDocument[];
  embedding: EmbeddingDescriptor;
  chunkerOptions: ChunkerOptions;
  strategies: readonly IndexedStrategy[];
  modes: readonly Mode[];
  results: readonly RetrievalResult[];
}

export interface IndexedStrategy {
  strategy: Strategy;
  /** Chunks stored for the corpus under this strategy. */
  chunks: number;
}

export interface ComboSummary {
  strategy: Strategy;
  mode: Mode;
  summary: Summary;
}

/** The per-type table and the misses list use this cut-off and mode. */
const FOCUS_K = 5;
const FOCUS_MODE: RetrievalMode = 'hybrid';

export function summarizeCombos(input: ReportInput): ComboSummary[] {
  const find = resultLookup(input.results);
  return input.strategies.flatMap(({ strategy }) =>
    input.modes.map((mode) => {
      const ranks = input.questions.map((q) => find(q.id, strategy.id, mode.id).rank);
      return { strategy, mode, summary: summarize(ranks, HIT_KS, RETRIEVAL.matchCount) };
    }),
  );
}

export function buildMarkdown(input: ReportInput): string {
  const sections = [
    header(input),
    whatIsMeasured(),
    setup(input),
    mainResults(input),
    byType(input),
    rankMatrix(input),
    misses(input),
    limitations(input),
    reproduce(),
  ];
  return `${sections.join('\n\n')}\n`;
}

/** Plain-text version of the main table for the terminal. */
export function buildConsoleTable(input: ReportInput): string {
  const { headers, rows } = metricsTable(input);
  const widths = headers.map((h, i) =>
    Math.max(h.length, ...rows.map((row) => cellAt(row, i).length)),
  );
  const line = (cells: readonly string[]) =>
    cells
      .map((cell, i) => cell.padEnd(widths[i] ?? 0))
      .join('  ')
      .trimEnd();
  return [line(headers), line(widths.map((w) => '-'.repeat(w))), ...rows.map(line)].join('\n');
}

function header(input: ReportInput): string {
  const lines = [
    '# Retrieval evaluation',
    '',
    `Generated by \`npm run eval\` on ${formatDate(input.generatedAt)} at ${describeCommit(input.commit)}. ` +
      'Do not edit this file by hand: every number in it comes from that run.',
  ];
  if (!input.isRealSet) {
    lines.push(
      '',
      `> **Template questions only.** \`fixtures/questions.json\` does not exist yet, so this run used the ` +
        `${input.questions.length} format examples in \`${input.questionFile}\`. ` +
        'The numbers show that the pipeline works end to end; they say almost nothing about retrieval quality.',
    );
  }
  return lines.join('\n');
}

function whatIsMeasured(): string {
  const k = RETRIEVAL.matchCount;
  return [
    '## What is measured',
    '',
    `Each question names the document that answers it and a short answer span copied word for word from that document. ` +
      `For every question the evaluation retrieves the top ${k} chunks and records the rank of the first chunk that comes ` +
      'from the right document and contains the answer span. Markdown formatting (table pipes, emphasis, backticks), ' +
      'line breaks and letter case are ignored in that comparison, because chunks are stored as raw markdown, ' +
      'and the span must not start or end in the middle of a word.',
    '',
    '- **hit@k**: how many questions have their answer within the first k chunks.',
    `- **MRR@${k}** (mean reciprocal rank): the average of 1/rank over all questions, with 0 for an answer not in the top ${k}. ` +
      '1.000 means every answer came first; 0.500 is what you get if every answer came second.',
    '',
    'Two chunking strategies are crossed with three retrieval modes:',
    '',
    '- **Structure-aware** (`chunkMarkdown`): a new chunk at every heading, code blocks and tables kept whole when they fit, ' +
      'and the heading path ("Leave policy > Parental leave") stored with each chunk.',
    '- **Naive fixed-size** (`chunkFixedSize`): a window of fixed size slid over the raw text, ignoring headings, tables and code.',
    '- **Vector**: cosine similarity between the question embedding and the chunk embeddings.',
    '- **Keyword**: Postgres full-text search over the chunk text, heading path and document title.',
    '- **Hybrid**: both lists fused with Reciprocal Rank Fusion, the mode the chat uses.',
    '',
    'Both strategies embed the same header in front of each chunk: the document title, then the heading path when there is one ' +
      '(naive chunks have none). Each strategy is indexed under its own user and searched as that user, so Row Level Security ' +
      'keeps the two indexes apart, exactly as it separates real users.',
  ].join('\n');
}

function setup(input: ReportInput): string {
  const { embedding, chunkerOptions: options } = input;
  const byType = QUESTION_TYPES.map(
    (type) => `${type} ${input.questions.filter((q) => q.type === type).length}`,
  ).join(', ');
  const prefixes =
    embedding.documentPrefix || embedding.queryPrefix
      ? `, prefixes \`${embedding.documentPrefix}\` (chunks) and \`${embedding.queryPrefix}\` (questions)`
      : ', no task prefixes';
  const rows = [
    [
      'Corpus',
      `${input.corpus.length} documents of the fictional company Quaylark Systems (\`fixtures/corpus/\`)`,
    ],
    ['Questions', `${input.questions.length} from \`${input.questionFile}\` (${byType})`],
    [
      'Embedding model',
      `\`${embedding.model}\` via ${embedding.provider}, ${embedding.dimensions} dimensions${prefixes}`,
    ],
    [
      'Chunk sizes',
      `target ${options.targetChars} characters, hard limit ${options.maxChars} including the header, ` +
        `overlap ${options.overlapChars}`,
    ],
    [
      'Chunks stored',
      input.strategies
        .map(({ strategy, chunks }) => `${strategy.label.toLowerCase()} ${chunks}`)
        .join(', '),
    ],
    [
      'Retrieval',
      `top ${RETRIEVAL.matchCount} chunks per question; each arm ranks up to ${RETRIEVAL.candidateCount} candidates; ` +
        `RRF k = ${RETRIEVAL.rrfK}`,
    ],
    [
      'Mode weights',
      input.modes
        .map((mode) => `${mode.id} ${mode.semanticWeight}/${mode.fullTextWeight}`)
        .join(', ') + ' (vector/keyword)',
    ],
  ];
  return ['## Setup', '', table(['Setting', 'Value'], rows)].join('\n');
}

function mainResults(input: ReportInput): string {
  const { headers, rows } = metricsTable(input);
  return ['## Results', '', table(headers, rows)].join('\n');
}

/** One row per strategy and mode: hit@k for each k, then MRR. */
function metricsTable(input: ReportInput): { headers: string[]; rows: string[][] } {
  const rows = summarizeCombos(input).map(({ strategy, mode, summary }) => [
    strategy.label,
    mode.id,
    ...summary.hitAt.map(({ rate }) => formatRate(rate)),
    formatMrr(summary.mrr),
  ]);
  const headers = ['Chunking', 'Retrieval', ...HIT_KS.map((k) => `hit@${k}`), mrrLabel()];
  return { headers, rows };
}

function byType(input: ReportInput): string {
  const find = resultLookup(input.results);
  const rows = QUESTION_TYPES.map((type) => {
    const questions = input.questions.filter((q) => q.type === type);
    return [
      type,
      String(questions.length),
      ...input.strategies.map(({ strategy }) => {
        const ranks = questions.map((q) => find(q.id, strategy.id, FOCUS_MODE).rank);
        return formatRate(hitAtK(ranks, FOCUS_K));
      }),
    ];
  });
  const headers = [
    'Question type',
    'Questions',
    ...input.strategies.map(({ strategy }) => strategy.label),
  ];
  return [
    `## ${capitalize(FOCUS_MODE)} hit@${FOCUS_K} by question type`,
    '',
    table(headers, rows),
  ].join('\n');
}

function rankMatrix(input: ReportInput): string {
  const find = resultLookup(input.results);
  const combos = input.strategies.flatMap(({ strategy }) =>
    input.modes.map((mode) => ({ strategy, mode })),
  );
  const headers = [
    'Question',
    'Type',
    ...combos.map(({ strategy, mode }) => `${strategy.shortLabel} ${mode.id}`),
  ];
  const rows = input.questions.map((q) => [
    q.id,
    q.type,
    ...combos.map(({ strategy, mode }) => formatRank(find(q.id, strategy.id, mode.id).rank)),
  ]);
  return [
    '## Rank of the first hit, per question',
    '',
    `A number is the rank of the first chunk that holds the answer; a dash means it was not in the top ${RETRIEVAL.matchCount}. ` +
      `Columns: ${input.strategies.map(({ strategy }) => `${strategy.shortLabel} = ${strategy.label.toLowerCase()}`).join(', ')}.`,
    '',
    table(headers, rows),
  ].join('\n');
}

function misses(input: ReportInput): string {
  const find = resultLookup(input.results);
  const titleByFile = new Map(input.corpus.map((doc) => [doc.file, doc.title]));
  const rows: string[][] = [];
  for (const q of input.questions) {
    for (const { strategy } of input.strategies) {
      for (const mode of input.modes) {
        const result = find(q.id, strategy.id, mode.id);
        if (result.rank !== null && result.rank <= FOCUS_K) continue;
        rows.push([
          `${q.id}: ${q.question}`,
          q.document,
          strategy.label,
          mode.id,
          result.rank === null ? `not in top ${RETRIEVAL.matchCount}` : String(result.rank),
          describeChunk(result.top, titleByFile),
        ]);
      }
    }
  }
  const heading = `## Misses (answer not in the top ${FOCUS_K})`;
  if (rows.length === 0) {
    return [
      heading,
      '',
      `Every question had its answer in the top ${FOCUS_K} in every combination.`,
    ].join('\n');
  }
  return [
    heading,
    '',
    `${rows.length} of ${input.questions.length * input.strategies.length * input.modes.length} runs ` +
      `(${input.questions.length} questions, ${input.strategies.length * input.modes.length} combinations). ` +
      '"Ranked first instead" is the top result: its document and heading path, or its opening words for a naive chunk.',
    '',
    table(
      ['Question', 'Gold document', 'Chunking', 'Retrieval', 'First hit', 'Ranked first instead'],
      rows,
    ),
  ].join('\n');
}

function limitations(input: ReportInput): string {
  const n = input.questions.length;
  const step = Math.round(100 / n);
  return [
    '## Limitations',
    '',
    `The sample is small: ${n} question${n === 1 ? '' : 's'}, so one question moves a hit rate by about ${step} percentage points, ` +
      'and a gap of a few questions between two rows can be noise. ' +
      `The ${n} questions were generated with Claude (an LLM) from the corpus, deliberately paraphrased away from the ` +
      'wording of the documents, and every answer span was verified verbatim by `fixtures/verify-questions.mjs`. ' +
      'LLM-generated questions can still share vocabulary with the source and so flatter semantic search, and they come ' +
      'from a single generator; real users phrase things less predictably. ' +
      'A hit is decided by answer-span matching: a chunk that gives the answer in other words, or a span cut in two by a chunk boundary, ' +
      'counts as a miss, and a chunk that happens to contain the span counts as a hit even if it is not the best passage. ' +
      'Keyword scores often tie (several chunks share the top score, usually through a title or heading match); ' +
      '`hybrid_search` breaks those ties by content hash, so rankings are repeatable, but which tied chunk wins is arbitrary. ' +
      'The vector index (HNSW) is approximate as well. ' +
      `Only one embedding model (\`${input.embedding.model}\`) and one set of chunk sizes were tested; ` +
      'another model or other sizes could change the ranking of the strategies. ' +
      'This measures retrieval only, not the quality of the answers the chat model writes from the retrieved chunks.',
  ].join('\n');
}

function reproduce(): string {
  return [
    '## Reproduce',
    '',
    '```bash',
    'npm run eval',
    '```',
    '',
    'It needs the local stack from `npm run setup` (Supabase and the embedding model running). ' +
      'The first run embeds the corpus once per chunking strategy; later runs reuse the stored vectors by hash ' +
      'and only embed the questions. Questions come from `fixtures/questions.json` ' +
      '(check them with `node fixtures/verify-questions.mjs`).',
  ].join('\n');
}

type Lookup = (questionId: string, strategy: StrategyId, mode: RetrievalMode) => RetrievalResult;

function resultLookup(results: readonly RetrievalResult[]): Lookup {
  const key = (questionId: string, strategy: string, mode: string) =>
    `${questionId}\u0000${strategy}\u0000${mode}`;
  const index = new Map(results.map((r) => [key(r.questionId, r.strategy, r.mode), r]));
  return (questionId, strategy, mode) => {
    const result = index.get(key(questionId, strategy, mode));
    if (!result) throw new Error(`No result for ${questionId} (${strategy}, ${mode}).`);
    return result;
  };
}

function describeChunk(
  chunk: RetrievedChunk | null,
  titleByFile: ReadonlyMap<string, string>,
): string {
  if (!chunk) return 'no results';
  const path = withoutTitle(chunk.headingPath, titleByFile.get(chunk.documentFile));
  if (path) return `${chunk.documentFile} > ${path}`;
  return `${chunk.documentFile}: "${excerpt(chunk.content, 60)}"`;
}

/** Heading paths start with the document's own H1, which the file name already identifies. */
function withoutTitle(headingPath: string, title: string | undefined): string {
  const prefix = `${title} > `;
  if (title && headingPath === title) return '';
  return title && headingPath.startsWith(prefix) ? headingPath.slice(prefix.length) : headingPath;
}

function excerpt(text: string, maxChars: number): string {
  const plain = text
    .replace(/[|`*_#>]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (plain.length <= maxChars) return plain;
  const cut = plain.slice(0, maxChars);
  const lastSpace = cut.lastIndexOf(' ');
  return `${(lastSpace > maxChars / 2 ? cut.slice(0, lastSpace) : cut).trimEnd()}...`;
}

/** A markdown table with padded columns, readable as plain text too. */
function table(headers: readonly string[], rows: readonly (readonly string[])[]): string {
  const escaped = [headers, ...rows].map((row) => row.map(escapeCell));
  const widths = headers.map((_, i) => Math.max(3, ...escaped.map((row) => cellAt(row, i).length)));
  const line = (cells: readonly string[]) =>
    `| ${widths.map((w, i) => cellAt(cells, i).padEnd(w)).join(' | ')} |`;
  const [head, ...body] = escaped;
  return [line(head ?? []), line(widths.map((w) => '-'.repeat(w))), ...body.map(line)].join('\n');
}

function escapeCell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
}

function cellAt(row: readonly string[], index: number): string {
  return row[index] ?? '';
}

function formatRank(rank: Rank): string {
  return rank === null ? '-' : String(rank);
}

function mrrLabel(): string {
  return `MRR@${RETRIEVAL.matchCount}`;
}

function capitalize(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

function formatDate(date: Date): string {
  return `${date.toISOString().slice(0, 16).replace('T', ' ')} UTC`;
}

function describeCommit(commit: CommitInfo | null): string {
  if (!commit) return 'an unknown commit (not a git checkout)';
  const paths = EVAL_INPUT_PATHS.map((p) => `\`${p}\``);
  const dirty = commit.dirty
    ? `, with uncommitted changes under ${paths.slice(0, -1).join(', ')} or ${paths.at(-1)}`
    : '';
  return `commit \`${commit.hash}\`${dirty}`;
}
